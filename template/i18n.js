function detectLang() {
  const saved = localStorage.getItem("sb_lang");
  if (saved === "zh" || saved === "en") return saved;
  const nav = (navigator.language || navigator.userLanguage || "en").toLowerCase();
  return nav.startsWith("zh") ? "zh" : "en";
}

function getLang() {
  return window.__SB_LANG || detectLang();
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
}

function applyI18n(lang = getLang()) {
  window.__SB_LANG = lang;
  localStorage.setItem("sb_lang", lang);
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key) return;
    el.textContent = t(key);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key) return;
    el.setAttribute("placeholder", t(key));
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (!key) return;
    el.setAttribute("aria-label", t(key));
  });

  const titleKey = document.body.getAttribute("data-title-key");
  if (titleKey) document.title = t(titleKey);

  document.querySelectorAll("[data-i18n-lang-btn]").forEach((btn) => {
    btn.textContent = t("lang.label");
    btn.setAttribute("aria-label", lang === "zh" ? "Switch to English" : "切换到中文");
  });

  window.dispatchEvent(new CustomEvent("sb:langchange", { detail: { lang } }));
}

function toggleLang() {
  applyI18n(getLang() === "zh" ? "en" : "zh");
}

function initI18n() {
  applyI18n(detectLang());
  document.querySelectorAll("[data-i18n-lang-btn]").forEach((btn) => {
    btn.addEventListener("click", toggleLang);
  });
}

document.addEventListener("DOMContentLoaded", initI18n);

window.SB_I18N = { t, getLang, applyI18n, toggleLang, detectLang };
